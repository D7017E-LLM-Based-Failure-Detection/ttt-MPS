"""Generate docs/version0/instance-parameters.md: the parameters of every IOTest16 instance.

Labels come from the knowledge graph (station-types/*.yaml and component-types/control-console.yaml),
so they follow when facts there change. Re-run after editing the graph:

    .venv\\Scripts\\python tools\\v0_params.py
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
KG = ROOT / "docs" / "mps400"
OUT = ROOT / "docs" / "version0" / "instance-parameters.md"
MAX_LABEL = 48  # proposed STRING length for the labels

# instance: (device, PLC id, module pair, station type or None, exclusive pairs, pulse times)
INSTANCES = [
    ("DS", "PLC_DS", "plc-distributing", "1 + 2", "distributing", [(1, 2), (3, 4)], {2: "T#500ms"}),
    ("TS", "PLC_TS", "plc-testing", "1 + 2", "testing", [(0, 1)], {}),
    ("HS2", "PLC_HP", "plc-handling-processing", "1 + 2", "handling", [(0, 1)], {}),
    ("PS", "PLC_HP", "plc-handling-processing", "3 + 4", "processing", [(2, 3)], {1: "T#300ms"}),
    ("CV_AB", "PLC_CV", "plc-conveyor", "1 + 2", None, [], {}),
    ("CV_CD", "PLC_CV", "plc-conveyor", "3 + 4", None, [], {}),
    ("HS6", "PLC_HS", "plc-handling-sorting", "1 + 2", "handling", [(0, 1)], {}),
    ("SS", "PLC_HS", "plc-handling-sorting", "3 + 4", "sorting", [], {}),
]


# Short texts for the control console (component-types/control-console.yaml has the full ones).
PANEL_IN = ["S1 START", "S2 STOP (NC)", "S3 AUTO/MAN", "S4 RESET", "external", "external E-stop", "external", "external"]
PANEL_OUT = ["P1 START lamp", "P2 RESET lamp", "P3 lamp", "P4 lamp", "external", "external", "external", "external"]


def load(rel):
    with (KG / rel).open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def label(*parts):
    text = " ".join(p for p in parts if p)
    return text if len(text) <= MAX_LABEL else text[: MAX_LABEL - 1] + "…"


def main():
    lines = [
        "# Version 0 — parameters per `IOTest16` instance",
        "",
        "Generated by `tools/v0_params.py` from the knowledge graph in `docs/mps400/`. Do not edit by hand; edit the graph and re-run.",
        "",
        f"Labels are cut to {MAX_LABEL} characters (proposed STRING length). `Excl` = the partner output that must never be on at the same time (`-1` = none). `Pulse` = automatic switch-off time (`T#0s` = toggle).",
        "",
        "Inputs and outputs marked ⚠ are to be checked on the hardware (their legacy name contradicts Festo's drawing).",
        "",
    ]
    for inst, device, plc, pair, stype, excl_pairs, pulses in INSTANCES:
        excl = {}
        for a, b in excl_pairs:
            excl[a], excl[b] = b, a
        lines += [f"## `{inst}` — device `{device}` ({plc}), modules {pair}", ""]
        if stype is None:
            lines += [
                "Conveyor channels are not assigned yet (question `q-connectors`). Use the channel names as labels "
                "(`DI00` …, `DO00` …) and fill in the Conveyor sheet of `wiring-check.xlsx` during the test.",
                "",
            ]
            continue
        st = load(f"station-types/{stype}.yaml")
        sig_in = {s["address"]: s for s in st["signals"]["inputs"]}
        sig_out = {s["address"]: s for s in st["signals"]["outputs"]}
        check = ("⚠ " if stype in ("processing", "sorting") else "")
        lines += ["| Channel | `LabelDIxx` | Channel | `LabelDOxx` | `ExclDOxx` | `PulseDOxx` |", "|---|---|---|---|---|---|"]
        for ch in range(16):
            if ch < 8:
                si, so = sig_in[f"I{ch}"], sig_out[f"O{ch}"]
                mark = check if ch in (1, 2) else ""
                li = mark + label(f"I{ch}", si.get("symbol"), si["meaning"])
                lo = label(f"O{ch}", so.get("symbol"), so["meaning"]) if so.get("symbol") else label(f"O{ch}", "spare")
            else:
                li = label(f"Panel I{ch - 8}", PANEL_IN[ch - 8])
                lo = label(f"Panel Q{ch - 8}", PANEL_OUT[ch - 8])
            lines.append(f"| DI{ch:02d} | {li} | DO{ch:02d} | {lo} | {excl.get(ch, -1)} | {pulses.get(ch, 'T#0s')} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("written", OUT)


if __name__ == "__main__":
    main()
